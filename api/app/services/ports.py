"""Interfaces services expect from repositories (implemented by app.repositories and the test fakes)."""

from typing import Protocol

from app.gen.oj.v1 import runner_pb2, types_pb2
from app.repositories.records import SubmissionFilter, SubmissionUpdate


class Database(Protocol):
    def ping(self) -> None: ...


class Problems(Protocol):
    def list_problems(self) -> list[types_pb2.Problem]: ...
    def get_problem(self, problem_id: int) -> types_pb2.Problem: ...
    def create_problem(
        self, problem: types_pb2.Problem, test_cases: list[types_pb2.TestCase]
    ) -> tuple[types_pb2.Problem, list[types_pb2.TestCase]]: ...
    def update_problem(self, problem: types_pb2.Problem) -> types_pb2.Problem: ...
    def delete_problem(self, problem_id: int) -> None: ...
    def list_test_cases(self, problem_id: int, samples_only: bool = False) -> list[types_pb2.TestCase]: ...
    def create_test_case(self, test_case: types_pb2.TestCase) -> types_pb2.TestCase: ...
    def delete_test_case(self, problem_id: int, test_case_id: int) -> None: ...


class Submissions(Protocol):
    def create_submission(self, submission: types_pb2.Submission) -> types_pb2.Submission: ...
    def get_submission(self, submission_id: int) -> types_pb2.Submission: ...
    def list_submissions(self, f: SubmissionFilter) -> list[types_pb2.Submission]: ...
    def update_submission(self, u: SubmissionUpdate) -> types_pb2.Submission: ...


class Queue(Protocol):
    def publish_submission_job(self, job: runner_pb2.ExecuteJob) -> None: ...
    def run_job(self, job: runner_pb2.ExecuteJob, timeout_s: float) -> runner_pb2.ExecuteResult: ...
    def queue_stats(self) -> tuple[int, int]: ...
